create or replace function public.is_platform_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.platform_admins
    where user_id = (select auth.uid())
  );
$$;

create or replace function public.has_store_access(target_store_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_platform_admin() or exists (
    select 1
    from public.store_members member
    join public.stores store on store.id = member.store_id
    where member.store_id = target_store_id
      and member.user_id = (select auth.uid())
      and member.active = true
      and store.status = 'active'
  );
$$;

create or replace function public.can_manage_store(target_store_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_platform_admin() or exists (
    select 1
    from public.store_members member
    join public.stores store on store.id = member.store_id
    where member.store_id = target_store_id
      and member.user_id = (select auth.uid())
      and member.active = true
      and member.role in ('owner','manager')
      and store.status = 'active'
  );
$$;

create or replace function public.resolve_public_store(requested_slug text default null, requested_hostname text default null)
returns table (
  id uuid,
  name text,
  slug text,
  is_demo boolean,
  primary_hostname text
)
language sql
stable
security definer
set search_path = public
as $$
  select
    store.id,
    store.name,
    store.slug,
    store.is_demo,
    (
      select domain.hostname
      from public.store_domains domain
      where domain.store_id = store.id
        and domain.status = 'active'
      order by domain.is_primary desc, domain.created_at asc
      limit 1
    ) as primary_hostname
  from public.stores store
  where store.status = 'active'
    and store.storefront_enabled = true
    and (
      (requested_slug is not null and store.slug = lower(trim(requested_slug)))
      or exists (
        select 1 from public.store_domains domain
        where domain.store_id = store.id
          and domain.status = 'active'
          and domain.hostname = lower(trim(requested_hostname))
      )
    )
  limit 1;
$$;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

